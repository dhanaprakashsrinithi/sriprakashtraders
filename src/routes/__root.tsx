function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const isAdminPage = useRouterState({ select: (state) => state.location.pathname.replace(/\/$/, "") === "/admin" });

  return (
    <QueryClientProvider client={queryClient}>
      <div className="flex min-h-screen flex-col">
        {isAdminPage ? (
          <header className="border-b border-border bg-background">
            <div className="container-site flex min-h-18 flex-wrap items-center justify-between gap-3 py-3">
              <Logo />
              <span className="text-sm font-semibold text-forest">Admin Dashboard</span>
            </div>
          </header>
        ) : <SiteHeader />}
        <main className="flex-1">
          {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
          <Outlet />
        </main>
        {!isAdminPage && <SiteFooter />}
      </div>
      {!isAdminPage && <WhatsAppFab />}
      <Toaster richColors position="top-center" />
    </QueryClientProvider>
  );
}
